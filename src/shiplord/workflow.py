"""Render the GitHub Actions release pipeline for an application (client-side).

The pipeline is two files: a reusable deploy workflow (``on: workflow_call``) that builds and deploys, and a
trigger workflow that calls it and optionally runs a quality workflow first. Both are generated from the same
inputs, so the same manifest always produces the same bytes.
"""

from __future__ import annotations

import json
import re

from . import __version__
from .manifest import configured_branch

TOOLING_REPOSITORY = "QueryPlanner/shiplord"
WORKFLOW_PATH = ".github/workflows/shiplord-release.yml"
DEPLOY_WORKFLOW_PATH = ".github/workflows/shiplord-deploy.yml"
DEFAULT_QUALITY_WORKFLOW = ".github/workflows/code-quality.yml"
_COMMIT = re.compile(r"[0-9a-f]{40}\Z")
_PLATFORMS = re.compile(r"linux/(amd64|arm64)(,linux/(amd64|arm64))?\Z")
_QUALITY_WORKFLOW = re.compile(r"\.github/workflows/[A-Za-z0-9_.-]+\.ya?ml\Z")

# Every action is pinned to a full commit; the comment names the release the commit belongs to.
ACTIONS = {
    "checkout": "actions/checkout@11d5960a326750d5838078e36cf38b85af677262 # v4",
    "python": "actions/setup-python@a26af69be951a213d495a4c3e4e4022e16d87065 # v5",
    "qemu": "docker/setup-qemu-action@c7c53464625b32c7a7e944ae62b3e17d2b600130 # v3",
    "buildx": "docker/setup-buildx-action@8d2750c68a42422c14e847fe6c8ac0403b4cbd6f # v3",
    "login": "docker/login-action@c94ce9fb468520275223c153574b00df6fe4bcc9 # v3",
    "metadata": "docker/metadata-action@c299e40c65443455700f0fdfc63efafe5b349051 # v5",
    "build": "docker/build-push-action@ca052bb54ab0790a636c9b5f226502c73d547a25 # v5",
    "tailscale": "tailscale/github-action@99a8333667fff04fdd6cffb46dfd409f8329a7bf # v4.3.0",
}


class WorkflowError(ValueError):
    """The workflow cannot be generated for this manifest."""


def validate_quality_workflow(path: object) -> str:
    """Return a quality workflow path that is safe to reference, or raise ``WorkflowError``.

    Only a reusable workflow file inside ``.github/workflows`` may be called, and never one Shiplord
    generates: a pipeline cannot call itself.
    """
    if not isinstance(path, str) or not _QUALITY_WORKFLOW.fullmatch(path) or path in (WORKFLOW_PATH, DEPLOY_WORKFLOW_PATH):
        raise WorkflowError("the quality workflow must be a reusable workflow file under .github/workflows/, "
                            "and not a workflow Shiplord generates")
    return path


def _validate(manifest: dict, tooling_ref: str, platforms: str, tooling_repository: str) -> None:
    if manifest["runtime"] != "docker":
        raise WorkflowError("workflow generation is available for Docker applications; for a native binary, call "
                            "`shiplord deploy --binary` from your own build job")
    if not _COMMIT.fullmatch(tooling_ref):
        raise WorkflowError("the tooling reference must be a full 40-character commit SHA")
    if not _PLATFORMS.fullmatch(platforms):
        raise WorkflowError("platforms must be linux/amd64, linux/arm64, or both separated by a comma")
    if not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", tooling_repository):
        raise WorkflowError("invalid tooling repository")



def _header() -> str:
    return (f"# Generated by Shiplord {__version__}. `shiplord github setup` regenerates this file; "
            "review changes in a pull request.\n")


def render_deploy_workflow(manifest: dict, *, tooling_ref: str, tooling_repository: str = TOOLING_REPOSITORY,
                           platforms: str = "linux/amd64") -> str:
    """Return the reusable deploy workflow. Deterministic: the same inputs always produce the same bytes."""
    _validate(manifest, tooling_ref, platforms, tooling_repository)
    branch = configured_branch(manifest)
    branch_ref = ("refs/heads/" + branch).replace("'", "''")
    quote = json.dumps
    qemu = f"      - uses: {ACTIONS['qemu']}\n" if "arm64" in platforms else ""
    # The deploy job's tailnet, SSH, deploy and summary steps live in this repository's composite action,
    # pinned to the same commit as the Shiplord this workflow installs.
    action = f"{tooling_repository}/deploy@{tooling_ref} # v1"
    return _header() + f"""name: Shiplord deploy

on:
  workflow_call:
    inputs:
      check_only:
        description: Check CI access only (Tailscale, SSH, helper); build and deploy nothing
        type: boolean
        default: false
    secrets:
      SHIPLORD_SSH_PRIVATE_KEY:
        required: true

permissions:
  contents: read

jobs:
  build:
    if: ${{{{ !inputs.check_only }}}}
    runs-on: ubuntu-24.04
    timeout-minutes: 30
    permissions:
      contents: read
      packages: write
    outputs:
      digest: ${{{{ steps.build-push.outputs.digest }}}}
      image: ${{{{ steps.name.outputs.image }}}}
    steps:
      - uses: {ACTIONS['checkout']}
        with:
          persist-credentials: false
      - name: Image name
        id: name
        run: echo "image=ghcr.io/${{GITHUB_REPOSITORY,,}}" >> "$GITHUB_OUTPUT"
{qemu}      - uses: {ACTIONS['buildx']}
      - uses: {ACTIONS['login']}
        with:
          registry: ghcr.io
          username: ${{{{ github.actor }}}}
          password: ${{{{ secrets.GITHUB_TOKEN }}}}
      - name: Image metadata
        id: meta
        uses: {ACTIONS['metadata']}
        with:
          images: ${{{{ steps.name.outputs.image }}}}
          tags: type=sha,format=long
      - name: Build and push
        id: build-push
        uses: {ACTIONS['build']}
        with:
          context: .
          push: true
          platforms: {platforms}
          tags: ${{{{ steps.meta.outputs.tags }}}}
          labels: |
            ${{{{ steps.meta.outputs.labels }}}}
            org.opencontainers.image.revision=${{{{ github.sha }}}}

  deploy:
    needs: build
    # Runs after a successful build, or alone for a check-only call (which skips the build).
    if: ${{{{ !cancelled() && github.ref == '{branch_ref}' && (inputs.check_only || needs.build.result == 'success') }}}}
    runs-on: ubuntu-24.04
    timeout-minutes: 30
    permissions:
      contents: read
      id-token: write
    steps:
      - uses: {ACTIONS['checkout']}
        with:
          ref: ${{{{ github.sha }}}}
          persist-credentials: false
      - name: Verify the checked-out commit
        run: test "$(git rev-parse HEAD)" = "$GITHUB_SHA"
      - uses: {ACTIONS['python']}
        with:
          python-version: "3.12"
      - name: Install the pinned Shiplord
        run: python -m pip install --disable-pip-version-check {quote(f"git+https://github.com/{tooling_repository}.git@{tooling_ref}")}
      - name: Deploy with Shiplord
        uses: {action}
        with:
          check-only: ${{{{ inputs.check_only }}}}
          ssh-private-key: ${{{{ secrets.SHIPLORD_SSH_PRIVATE_KEY }}}}
          ssh-known-hosts: ${{{{ vars.SHIPLORD_SSH_KNOWN_HOSTS }}}}
          deploy-user: ${{{{ vars.SHIPLORD_DEPLOY_USER }}}}
          server-host: ${{{{ vars.SHIPLORD_SERVER_HOST }}}}
          ssh-port: ${{{{ vars.SHIPLORD_SSH_PORT }}}}
          ts-client-id: ${{{{ vars.SHIPLORD_TS_CLIENT_ID }}}}
          ts-audience: ${{{{ vars.SHIPLORD_TS_AUDIENCE }}}}
          ts-tags: ${{{{ vars.SHIPLORD_TS_TAGS || 'tag:ci' }}}}
          image: ${{{{ needs.build.outputs.image }}}}
          digest: ${{{{ needs.build.outputs.digest }}}}
          commit: ${{{{ github.sha }}}}
          request-id: gh-${{{{ github.run_id }}}}-${{{{ github.run_attempt }}}}
"""


def render_workflow(manifest: dict, *, tooling_ref: str, tooling_repository: str = TOOLING_REPOSITORY,
                    platforms: str = "linux/amd64", quality_workflow: str | None = None) -> str:
    """Return the trigger workflow text. Deterministic: the same inputs always produce the same bytes.

    ``quality_workflow`` is a reusable workflow in this repository to run before deploy, or ``None`` for a
    pipeline with no quality job. It is never guessed here: the caller decides from the project.
    """
    _validate(manifest, tooling_ref, platforms, tooling_repository)
    quality = None if quality_workflow is None else validate_quality_workflow(quality_workflow)
    branch = configured_branch(manifest)
    app = manifest["name"]
    quote = json.dumps
    if quality is None:
        quality_job, deploy_needs, deploy_if = "", "", "    if: ${{ !cancelled() }}\n"
    else:
        quality_job = (f"""  quality:
    if: ${{{{ !inputs.check_only }}}}
    permissions:
      contents: read
      id-token: write
    uses: ./{quality}

""")
        deploy_needs = "    needs: quality\n"
        deploy_if = "    if: ${{ !cancelled() && (inputs.check_only || needs.quality.result == 'success') }}\n"
    return _header() + f"""name: Release

on:
  push:
    branches: [{quote(branch)}]
  workflow_dispatch:
    inputs:
      check_only:
        description: Check CI access only (Tailscale, SSH, helper); build and deploy nothing
        type: boolean
        default: false

permissions:
  contents: read

# Production releases run one at a time and are never cancelled half way.
concurrency:
  group: {quote("shiplord-release-" + app)}
  cancel-in-progress: false

jobs:
{quality_job}  deploy:
{deploy_needs}{deploy_if}    permissions:
      contents: read
      id-token: write
      packages: write
    uses: ./{DEPLOY_WORKFLOW_PATH}
    with:
      check_only: ${{{{ inputs.check_only }}}}
    secrets:
      SHIPLORD_SSH_PRIVATE_KEY: ${{{{ secrets.SHIPLORD_SSH_PRIVATE_KEY }}}}
"""
